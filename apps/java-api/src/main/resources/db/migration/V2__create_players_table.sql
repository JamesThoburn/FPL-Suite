CREATE TABLE IF NOT EXISTS players (
    id INTEGER PRIMARY KEY,
    code INTEGER NOT NULL,
    first_name TEXT NOT NULL,
    second_name TEXT NOT NULL,
    web_name TEXT NOT NULL,
    element_type_id SMALLINT NOT NULL,
    team_id INTEGER NOT NULL REFERENCES teams(id),
    now_cost SMALLINT NOT NULL,
    status CHAR(1) NOT NULL,
    chance_of_playing_next_round SMALLINT,
    news TEXT,
    total_points INTEGER NOT NULL,
    form NUMERIC(5,2),
    selected_by_percent NUMERIC(5,2),
    minutes INTEGER,
    goals_scored INTEGER,
    assists INTEGER,
    clean_sheets INTEGER,
    goals_conceded INTEGER,
    own_goals INTEGER,
    penalties_saved INTEGER,
    penalties_missed INTEGER,
    yellow_cards INTEGER,
    red_cards INTEGER,
    saves INTEGER,
    bonus INTEGER,
    bps INTEGER,
    expected_goals NUMERIC(7,3),
    expected_assists NUMERIC(7,3),
    expected_goal_involvements NUMERIC(7,3),
    expected_goals_conceded NUMERIC(7,3)
);